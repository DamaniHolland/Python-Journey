# The Modulo Operator

'''
THe Modulo Operator(%):

    - Divides one number by another and returns the remainder.
'''

    # x is the number to be divided
x = 4

    # y is the number to divide by
y = 3

    # the remainder should be 1 assigned to 'z'
z= x % y

print('The remainder of ' + str(x) + ' % ' + str(y) + ' is ' + str(z))